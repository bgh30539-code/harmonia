// repository (FOSS-style signing, see docs/INSTALL.md) so that CI and local
// builds produce installable, update-consistent artifacts.
val keystoreProperties = Properties().apply {
    val propFile = file("keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

